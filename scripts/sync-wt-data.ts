async function syncWTData() {
  console.log("=== War Thunder Verified Data Sync Pipeline ===");
  const dataDir = path.resolve(__dirname, "../data");
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  const vehiclesMap = new Map<string, Vehicle>();

  // 1. Populate initial verified seeds
  for (const v of VERIFIED_SEEDS) {
    vehiclesMap.set(v.id, v);
  }

  // 2. Fetch authoritative datamine wpcost.blkx
  try {
    console.log("Fetching live War Thunder Datamine wpcost.blkx...");
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 10000);

    const res = await fetch(
      "https://raw.githubusercontent.com/gszabi99/War-Thunder-Datamine/master/char.vromfs.bin_u/config/wpcost.blkx",
      { signal: controller.signal }
    );
    clearTimeout(timeout);

    if (res.ok) {
      const data = (await res.json()) as Record<string, WPCostUnit>;
      console.log(`Loaded ${Object.keys(data).length} total raw game entities from datamine.`);

      // Update existing seeds with exact economic ranks if present
      for (const [id, unit] of Object.entries(data)) {
        if (!unit || typeof unit !== "object") continue;

        // Check if we have this vehicle in our verified set
        const existing = vehiclesMap.get(id);
        if (existing) {
          const ab = unit.economicRankArcade !== undefined ? economicRankToBR(unit.economicRankArcade) : existing.br.ab;
          const rb = unit.economicRankHistorical !== undefined ? economicRankToBR(unit.economicRankHistorical) : existing.br.rb;
          const sb = unit.economicRankSimulation !== undefined ? economicRankToBR(unit.economicRankSimulation) : existing.br.sb;

          vehiclesMap.set(id, {
            ...existing,
            rank: unit.rank ?? existing.rank,
            br: { ab, rb, sb },
            isPremium: existing.isPremium || unit.costGold !== undefined || unit.isGift === true,
          });
        }
      }
      console.log("Successfully verified and synchronized vehicles against live Datamine.");
    }
  } catch (err: unknown) {
    console.warn("Datamine fetch timed out or failed; retaining verified authoritative seeds:", (err as Error).message);
  }

  const finalVehicles = Array.from(vehiclesMap.values());
  console.log(`Saving ${finalVehicles.length} verified vehicles to data/vehicles.json...`);

  fs.writeFileSync(
    path.join(dataDir, "vehicles.json"),
    JSON.stringify(finalVehicles, null, 2),
    "utf-8"
  );

  console.log("Done syncing vehicles database.");
}

syncWTData().catch((err) => {
  console.error("Failed to sync WT data:", err);
  process.exit(1);
});
